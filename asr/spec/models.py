from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field, model_validator


class Constraint(BaseModel):
    name: str
    description: str = ""
    type: str = "must"


class AcceptanceCriteria(BaseModel):
    name: str
    description: str = ""
    expected_behavior: str = ""


class Feature(BaseModel):
    name: str
    description: str = ""


class ValidationResult(BaseModel):
    valid: bool = True
    errors: list[str] = Field(default_factory=list)


class Specification(BaseModel):
    goal: str = ""
    constraints: list[Constraint] = Field(default_factory=list)
    acceptance: list[AcceptanceCriteria] = Field(default_factory=list)
    features: list[Feature] = Field(default_factory=list)

    @model_validator(mode="before")
    @classmethod
    def _normalize_projection(cls, data: Any) -> Any:
        """Normalize minimal spec projections (e.g. generated by ousheng
        work-item descriptions).

        Accepts:
        - ``acceptance_criteria`` as an alias for ``acceptance``
        - plain strings in acceptance lists (coerced to AcceptanceCriteria)
        """
        if isinstance(data, dict):
            if "acceptance" not in data and "acceptance_criteria" in data:
                data = {**data, "acceptance": data["acceptance_criteria"]}
            if isinstance(data.get("acceptance"), list):
                data = {**data, "acceptance": [
                    {"name": item} if isinstance(item, str) else item
                    for item in data["acceptance"]
                ]}
        return data

    def validate_spec(self) -> ValidationResult:
        errors = []
        if not self.goal:
            errors.append("goal is required")
        return ValidationResult(valid=len(errors) == 0, errors=errors)
